    [Fact]
    public void CompilationBlueprint_serialization_round_trips_and_writes_atomically()
    {
        var tempDir = Path.Combine(Path.GetTempPath(), "fuse-bp-unit-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempDir);
        try
        {
            var project = new CompilationBlueprint.BlueprintProject(
                ProjectPath: "App/App.csproj",
                Name: "App",
                AssemblyName: "App",
                Compile:
                [
                    new CompilationBlueprint.BlueprintDocument("App/Program.cs", [], InlineText: null),
                    new CompilationBlueprint.BlueprintDocument("App/obj/Debug/net10.0/App.GlobalUsings.g.cs", ["obj", "Debug", "net10.0"], "// <autogenerated />\n"),
                ],
                ReferencePath: ["Lib/bin/Debug/net10.0/Lib.dll"],
                Analyzer: [],
                AdditionalFiles: [new CompilationBlueprint.BlueprintDocument("App/PublicAPI.Shipped.txt", [], InlineText: null)],
                AnalyzerConfigFiles: [new CompilationBlueprint.BlueprintDocument("App/obj/Debug/net10.0/App.GeneratedMSBuildEditorConfig.editorconfig", ["obj"], "is_global = true\n")],
                DefineConstants: ["TRACE", "DEBUG"],
                LanguageVersion: "Preview",
                OutputKind: nameof(OutputKind.ConsoleApplication),
                Nullable: nameof(NullableContextOptions.Enable),
                AllowUnsafe: true,
                SpecificDiagnosticOptions: new Dictionary<string, string>(StringComparer.Ordinal) { ["CS1591"] = nameof(ReportDiagnostic.Suppress) },
                OutputPath: "App/bin/Debug/net10.0/App.dll",
                ProjectReferences: [new CompilationBlueprint.BlueprintProjectReference("Lib/Lib.csproj", "Lib", [], EmbedInteropTypes: false)],
                TargetFramework: "net10.0",
                IsTestProject: false,
                TestFramework: default,
                OutputRefPath: "App/obj/Debug/net10.0/ref/App.dll");

            var blueprint = new CompilationBlueprint(
                CompilationBlueprint.FormatVersion,
                CompilationBlueprint.CurrentBuild,
                "KEY1234",
                tempDir,
                new Dictionary<string, string>(StringComparer.Ordinal) { ["App/App.csproj"] = "ABC" },
                new Dictionary<string, string>(StringComparer.Ordinal) { ["App/obj/project.assets.json"] = "DEF" },
                [project]);

            var targetFile = CompilationBlueprint.FileFor(tempDir, blueprint.Key);
            Assert.True(blueprint.TryWrite(targetFile));

            var loaded = CompilationBlueprint.TryReadFile(targetFile);
            Assert.NotNull(loaded);
            Assert.Equal(blueprint.Key, loaded.Key);
            Assert.Equal(blueprint.SourceRoot, loaded.SourceRoot);
            Assert.Equal("ABC", loaded.InputHashes["App/App.csproj"]);
            Assert.Equal("DEF", loaded.AssetsHashes["App/obj/project.assets.json"]);
            var loadedProj = Assert.Single(loaded.Projects);
            Assert.Equal(nameof(OutputKind.ConsoleApplication), loadedProj.OutputKind);
            Assert.Equal(nameof(NullableContextOptions.Enable), loadedProj.Nullable);
            Assert.True(loadedProj.AllowUnsafe);
            Assert.Equal("net10.0", loadedProj.TargetFramework);
            Assert.Equal(["TRACE", "DEBUG"], loadedProj.DefineConstants);
            Assert.Equal(nameof(ReportDiagnostic.Suppress), loadedProj.SpecificDiagnosticOptions["CS1591"]);
            Assert.Equal(2, loadedProj.Compile.Count);
            Assert.Equal("// <autogenerated />\n", loadedProj.Compile[1].InlineText);
            Assert.Single(loadedProj.ProjectReferences);
            Assert.Equal("Lib", loadedProj.ProjectReferences[0].TargetProjectName);

            for (var i = 0; i < 6; i++)
            {
                var copy = new CompilationBlueprint(
                    CompilationBlueprint.FormatVersion,
                    CompilationBlueprint.CurrentBuild,
                    $"PRUNE_{i}",
                    tempDir,
                    blueprint.InputHashes,
                    blueprint.AssetsHashes,
                    blueprint.Projects);
                Assert.True(copy.TryWrite(CompilationBlueprint.FileFor(tempDir, copy.Key)));
                Thread.Sleep(20);
            }

            CompilationBlueprint.Prune(tempDir);
            var remaining = Directory.GetFiles(CompilationBlueprint.DirectoryFor(tempDir), "*.json");
            Assert.Equal(4, remaining.Length);
        }
        finally
        {
            if (Directory.Exists(tempDir))
                Directory.Delete(tempDir, recursive: true);
        }
    }

