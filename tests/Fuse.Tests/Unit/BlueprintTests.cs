    [Fact]
    public void CompilationBlueprint_serialization_round_trips_and_writes_atomically()
    {
        var tempDir = Path.Combine(Path.GetTempPath(), "fuse-bp-unit-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(tempDir);
        try
        {
            var project = new CompilationBlueprint.BlueprintProject(
                ProjectPath: "App/App.csproj",
                Name: "App",
                AssemblyName: "App",
                Compile:
                [
                    new CompilationBlueprint.BlueprintDocument("App/Program.cs", [], InlineText: null),
                    new CompilationBlueprint.BlueprintDocument("App/obj/Debug/net10.0/App.GlobalUsings.g.cs", ["obj", "Debug", "net10.0"], "// <autogenerated />\n"),
                ],
                ReferencePath: ["Lib/bin/Debug/net10.0/Lib.dll"],
                Analyzer: [],
                AdditionalFiles: [new CompilationBlueprint.BlueprintDocument("App/PublicAPI.Shipped.txt", [], InlineText: null)],
                AnalyzerConfigFiles: [new CompilationBlueprint.BlueprintDocument("App/obj/Debug/net10.0/App.GeneratedMSBuildEditorConfig.editorconfig", ["obj"], "is_global = true\n")],
                DefineConstants: ["TRACE", "DEBUG"],
                LanguageVersion: "Preview",
                OutputKind: nameof(OutputKind.ConsoleApplication),
                Nullable: nameof(NullableContextOptions.Enable),
                AllowUnsafe: true,
                SpecificDiagnosticOptions: new Dictionary<string, string>(StringComparer.Ordinal) { ["CS1591"] = nameof(ReportDiagnostic.Suppress) },
                OutputPath: "App/bin/Debug/net10.0/App.dll",
                ProjectReferences: [new CompilationBlueprint.BlueprintProjectReference("Lib/Lib.csproj", "Lib", [], EmbedInteropTypes: false)],
                TargetFramework: "net10.0",
                IsTestProject: false,
                TestFramework: default,
                OutputRefPath: "App/obj/Debug/net10.0/ref/App.dll");

            var blueprint = new CompilationBlueprint(
                CompilationBlueprint.FormatVersion,
                CompilationBlueprint.CurrentBuild,
                "KEY1234",
                tempDir,
                new Dictionary<string, string>(StringComparer.Ordinal) { ["App/App.csproj"] = "ABC" },
                new Dictionary<string, string>(StringComparer.Ordinal) { ["App/obj/project.assets.json"] = "DEF" },
                [project]);

            var targetFile = CompilationBlueprint.FileFor(tempDir, blueprint.Key);
            Assert.True(blueprint.TryWrite(targetFile));

            var loaded = CompilationBlueprint.TryReadFile(targetFile);
            Assert.NotNull(loaded);
            Assert.Equal(blueprint.Key, loaded.Key);
            Assert.Equal(blueprint.SourceRoot, loaded.SourceRoot);
            Assert.Equal("ABC", loaded.InputHashes["App/App.csproj"]);
            Assert.Equal("DEF", loaded.AssetsHashes["App/obj/project.assets.json"]);
            var loadedProj = Assert.Single(loaded.Projects);
            Assert.Equal(nameof(OutputKind.ConsoleApplication), loadedProj.OutputKind);
            Assert.Equal(nameof(NullableContextOptions.Enable), loadedProj.Nullable);
            Assert.True(loadedProj.AllowUnsafe);
            Assert.Equal("net10.0", loadedProj.TargetFramework);
            Assert.Equal(["TRACE", "DEBUG"], loadedProj.DefineConstants);
            Assert.Equal(nameof(ReportDiagnostic.Suppress), loadedProj.SpecificDiagnosticOptions["CS1591"]);
            Assert.Equal(2, loadedProj.Compile.Count);
            Assert.Equal("// <autogenerated />\n", loadedProj.Compile[1].InlineText);
            Assert.Single(loadedProj.ProjectReferences);
            Assert.Equal("Lib", loadedProj.ProjectReferences[0].TargetProjectName);

            for (var i = 0; i < 6; i++)
            {
                var copy = new CompilationBlueprint(
                    CompilationBlueprint.FormatVersion,
                    CompilationBlueprint.CurrentBuild,
                    $"PRUNE_{i}",
                    tempDir,
                    blueprint.InputHashes,
                    blueprint.AssetsHashes,
                    blueprint.Projects);
                Assert.True(copy.TryWrite(CompilationBlueprint.FileFor(tempDir, copy.Key)));
                Thread.Sleep(20);
            }

            CompilationBlueprint.Prune(tempDir);
            var remaining = Directory.GetFiles(CompilationBlueprint.DirectoryFor(tempDir), "*.json");
            Assert.Equal(4, remaining.Length);
        }
        finally
        {
            if (Directory.Exists(tempDir))
                Directory.Delete(tempDir, recursive: true);
        }
    }

    [Fact]
    public async Task BlueprintEvaluator_EvaluateCliAsync_extracts_valid_blueprint_and_ephemerally_disposes_MSBuildWorkspace()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        await using var engine = await InProcessEngine.StartAsync();
        var outputPath = Path.Combine(engine.Repo.Root.SharedStateDirectory, "cli-eval-blueprint.json");

        var exitCode = await BlueprintEvaluator.EvaluateCliAsync([engine.Repo.Root.Path, outputPath], cancellationToken);

        Assert.Equal(0, exitCode);
        Assert.True(File.Exists(outputPath));
        var blueprint = CompilationBlueprint.TryReadFile(outputPath);
        Assert.NotNull(blueprint);
        Assert.Contains(blueprint.Projects, p => p.Name == "Lib");
        Assert.Contains(blueprint.Projects, p => p.Name == "App");
        Assert.Contains(blueprint.Projects, p => p.Name == "App.Tests" && p.IsTestProject);

        var appBlueprint = blueprint.Projects.Single(p => p.Name == "App");
        Assert.NotEmpty(appBlueprint.Compile);
        Assert.NotEmpty(appBlueprint.ReferencePath);
        Assert.Single(appBlueprint.ProjectReferences, r => r.TargetProjectName == "Lib");
    }

    [Fact]
    public async Task BlueprintWorkspace_loads_from_blueprint_supports_single_project_unload_and_falls_back_gracefully()
    {
        var cancellationToken = TestContext.Current.CancellationToken;
        await using var engine = await InProcessEngine.StartAsync();
        var graph = await RepoGraph.EvaluateAsync(engine.Repo.Root, cancellationToken);
        var app = graph.Projects.Single(p => p.Name == "App");
        var tests = graph.Projects.Single(p => p.Name == "App.Tests");

        var outcome = await BlueprintEvaluator.EnsureProjectsAsync(engine.Repo.Root, graph, [app, tests], _ => { }, cancellationToken);
        Assert.Empty(outcome.Failures);
        Assert.NotNull(outcome.Blueprint);

        using var workspace = new BlueprintWorkspace();
        workspace.LoadProjects(engine.Repo.Root, graph, outcome.Blueprint, [app, tests], engine.Workspace.Tracker.Head);

        Assert.True(workspace.IsLoaded(app.Path));
        Assert.True(workspace.IsLoaded(tests.Path));
        Assert.Equal(3, workspace.LoadedPaths().Count);

        var appCompilation = await workspace.Solution.Projects.Single(p => p.Name == "App").GetCompilationAsync(cancellationToken);
        Assert.NotNull(appCompilation);
        Assert.DoesNotContain(appCompilation.GetDiagnostics(cancellationToken), d => d.Severity == DiagnosticSeverity.Error);

        // Unload only App.Tests while leaving App and Lib loaded and compilable.
        var unloaded = workspace.UnloadProjects([tests.Path]);
        Assert.Equal([tests.Path], unloaded);
        Assert.False(workspace.IsLoaded(tests.Path));
        Assert.True(workspace.IsLoaded(app.Path));
        Assert.Equal(2, workspace.LoadedPaths().Count);

        // Verify exotic MSBuild ProjectInfo injection preserves single-project workspace semantics.
        var exoticId = ProjectId.CreateNewId("Exotic");
        var exoticFile = Path.Combine(engine.Repo.Root.Path, "Exotic", "Exotic.csproj");
        var exoticInfo = ProjectInfo.Create(exoticId, VersionStamp.Create(), "Exotic", "Exotic", LanguageNames.CSharp, filePath: exoticFile);
        workspace.AddExtractedProjects(engine.Repo.Root, [exoticInfo]);
        Assert.True(workspace.IsLoaded(engine.Repo.Root.PathOf(exoticFile)));
    }

    [Fact]
    public void EngineLauncher_configures_GC_memory_governance_and_preserves_caller_overrides()
    {
        var gb = 1024L * 1024 * 1024;
        Assert.Equal(768L * 1024 * 1024, EngineLauncher.ComputeHeapHardLimitBytes(1 * gb));
        Assert.Equal(1 * gb, EngineLauncher.ComputeHeapHardLimitBytes(4 * gb));
        Assert.Equal(2 * gb, EngineLauncher.ComputeHeapHardLimitBytes(32 * gb));
        Assert.Equal(1 * gb, EngineLauncher.ComputeHeapHardLimitBytes(0));

        var defaults = EngineLauncher.GcEnvironmentOverrides(_ => null, 8 * gb);
        Assert.Equal("9", defaults["DOTNET_GCConserveMemory"]);
        Assert.Equal("1", defaults["DOTNET_GCDynamicAdaptationMode"]);
        Assert.Equal("0x80000000", defaults["DOTNET_GCHeapHardLimit"]);

        var custom = EngineLauncher.GcEnvironmentOverrides(
            name => name == "DOTNET_GCHeapHardLimit" ? "0x40000000" : null,
            32 * gb);
        Assert.False(custom.ContainsKey("DOTNET_GCHeapHardLimit"));
        Assert.Equal("9", custom["DOTNET_GCConserveMemory"]);

        if (OperatingSystem.IsWindows())
        {
            var merged = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
            {
                ["PATH"] = "C:\\Windows",
                ["DOTNET_GCConserveMemory"] = "5",
            };
            foreach (var (k, v) in EngineLauncher.GcEnvironmentOverrides(merged.GetValueOrDefault, 8 * gb))
                merged[k] = v;

            var block = EngineLauncher.BuildWindowsEnvironmentBlock(merged);
            var text = new string(block);
            var entries = text.Split('\0', StringSplitOptions.RemoveEmptyEntries);
            Assert.Contains("DOTNET_GCConserveMemory=5", entries);
            Assert.Contains("DOTNET_GCDynamicAdaptationMode=1", entries);
            Assert.Contains("DOTNET_GCHeapHardLimit=0x80000000", entries);
            Assert.EndsWith("\0\0", text, StringComparison.Ordinal);
            Assert.NotNull(RuntimeInformation.FrameworkDescription);
        }
    }
