    [Fact]
    public void EngineLauncher_configures_GC_memory_governance_and_preserves_caller_overrides()
    {
        var gb = 1024L * 1024 * 1024;
        Assert.Equal(768L * 1024 * 1024, EngineLauncher.ComputeHeapHardLimitBytes(1 * gb));
        Assert.Equal(1 * gb, EngineLauncher.ComputeHeapHardLimitBytes(4 * gb));
        Assert.Equal(2 * gb, EngineLauncher.ComputeHeapHardLimitBytes(32 * gb));
        Assert.Equal(1 * gb, EngineLauncher.ComputeHeapHardLimitBytes(0));

        var defaults = EngineLauncher.GcEnvironmentOverrides(_ => null, 8 * gb);
        Assert.Equal("9", defaults["DOTNET_GCConserveMemory"]);
        Assert.Equal("1", defaults["DOTNET_GCDynamicAdaptationMode"]);
        Assert.Equal("0x80000000", defaults["DOTNET_GCHeapHardLimit"]);

        var custom = EngineLauncher.GcEnvironmentOverrides(
            name => name == "DOTNET_GCHeapHardLimit" ? "0x40000000" : null,
            32 * gb);
        Assert.False(custom.ContainsKey("DOTNET_GCHeapHardLimit"));
        Assert.Equal("9", custom["DOTNET_GCConserveMemory"]);

        if (OperatingSystem.IsWindows())
        {
            var merged = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
            {
                ["PATH"] = "C:\\Windows",
                ["DOTNET_GCConserveMemory"] = "5",
            };
            foreach (var (k, v) in EngineLauncher.GcEnvironmentOverrides(merged.GetValueOrDefault, 8 * gb))
                merged[k] = v;

            var block = EngineLauncher.BuildWindowsEnvironmentBlock(merged);
            var text = new string(block);
            var entries = text.Split('\0', StringSplitOptions.RemoveEmptyEntries);
            Assert.Contains("DOTNET_GCConserveMemory=5", entries);
            Assert.Contains("DOTNET_GCDynamicAdaptationMode=1", entries);
            Assert.Contains("DOTNET_GCHeapHardLimit=0x80000000", entries);
            Assert.EndsWith("\0\0", text, StringComparison.Ordinal);
            Assert.NotNull(RuntimeInformation.FrameworkDescription);
        }
    }

    private static void RunGit(string workingDirectory, params string[] arguments)
    {
        var psi = new ProcessStartInfo("git")
        {
            WorkingDirectory = workingDirectory,
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
        };
        foreach (var argument in arguments)
            psi.ArgumentList.Add(argument);
        using var process = Process.Start(psi)!;
        var stdout = process.StandardOutput.ReadToEnd();
        var stderr = process.StandardError.ReadToEnd();
        process.WaitForExit();
        if (process.ExitCode != 0)
            throw new InvalidOperationException($"git {string.Join(' ', arguments)} failed: {stderr}{stdout}");
    }

    private static void CleanupWorktree(string repoPath, string worktreeDir)
    {
        if (!Directory.Exists(worktreeDir))
            return;
        try
        {
            RunGit(repoPath, "worktree", "remove", "--force", worktreeDir);
        }
        catch
        {
            try
            {
                Directory.Delete(worktreeDir, recursive: true);
            }
            catch
            {
            }
        }
    }
